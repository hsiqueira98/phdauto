/**
 * As fotos vêm do manifesto gerado por `npm run fotos`, casadas pelo
 * fotoKey. Assim estoque e acervo evoluem separados: trocar as
 * fotografias não exige mexer nos dados do veículo.
 */
export const vehicles = catalogo.map((v) => ({
  ...v,
  photos: manifestoFotos[v.fotoKey] ?? [],
}));

export const getVehicleBySlug = (slug) => vehicles.find((v) => v.slug === slug);

export const featuredVehicles = vehicles.filter((v) => v.featured);

/** Recomendação simples por afinidade — universo, carroceria, marca e faixa de preço. */
export const getRelated = (vehicle, count = 3) =>
  vehicles
    .filter((v) => v.id !== vehicle.id)
    .map((v) => ({
      v,
      score:
        (v.universe === vehicle.universe ? 3 : 0) +
        (v.body === vehicle.body ? 2 : 0) +
        (v.brand === vehicle.brand ? 1 : 0) +
        (Math.abs(v.price - vehicle.price) < 30000 ? 2 : 0),
    }))
    .sort((a, b) => b.score - a.score)
    .slice(0, count)
    .map((x) => x.v);
